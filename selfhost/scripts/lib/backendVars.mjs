/**
 * Which environment variables get pushed INTO the Convex deployment.
 *
 * Extracted from bootstrap.mjs so it can be tested: the script itself is
 * top-level imperative and runs a real deploy on import.
 *
 * The Convex runtime is a separate environment from the app container's, so
 * anything read by code running inside Convex has to be pushed here. The
 * interesting part is what is deliberately NOT pushed:
 *
 *   VOYAGE_API_KEY / OPENAI_API_KEY were never pushed, which is why
 *   convex/documentChunks.ts threw INDEXING_UNAVAILABLE on every self-hosted
 *   install even though the installer had collected a Voyage key. That is fixed
 *   at the source now - those keys live in the aiCredentials table, in the same
 *   deployment that reads them, so there is nothing to push. Re-adding them here
 *   would reintroduce the two-sources-of-truth problem rather than fix anything.
 */
import { randomBytes } from 'node:crypto';

/** Read one KEY=value out of raw .env text. Returns '' when absent. */
export function readEnvValue(raw, key) {
  const match = String(raw ?? '').match(new RegExp(`^${key}=(.*)$`, 'm'));
  return match ? match[1].trim() : '';
}

/**
 * 32 random bytes, base64url so no '+', '/' or '=' survives a shell or a naive
 * .env parser. Matches what install.ps1 generates on Windows.
 */
export function generateServiceToken() {
  return randomBytes(32).toString('base64url');
}

/**
 * Vars whose absence must stop the bootstrap rather than merely skip a feature.
 * CLERK_JWT_ISSUER_DOMAIN is read by auth.config.ts at DEPLOY time, so the push
 * in the next step is rejected without it. AI_CREDENTIAL_SERVICE_TOKEN gates
 * every AI request in both runtimes.
 */
export const REQUIRED_BACKEND_VARS = ['AI_CREDENTIAL_SERVICE_TOKEN'];

/**
 * Additionally required, depending on AUTH_MODE.
 *
 * convex/auth.config.ts reads these at DEPLOY time and throws without them, so
 * a missing one rejects the push rather than producing an install that
 * authenticates nobody. Which set applies depends on who issues tokens:
 *
 *   local  the app server does; it publishes a JWKS on its own origin
 *   clerk  Clerk does - the hosted product, or a server-mode install with a
 *          real hostname
 *   both   either. A desktop install that lets the user pick a local account
 *          or their hosted AeroGap account at sign-in. Needs everything.
 */
export function requiredAuthVars(authMode) {
  const mode = String(authMode || 'clerk').trim();
  if (mode === 'local') return ['LOCAL_AUTH_ISSUER', 'LOCAL_AUTH_JWKS_URL'];
  if (mode === 'both') return ['CLERK_JWT_ISSUER_DOMAIN', 'LOCAL_AUTH_ISSUER', 'LOCAL_AUTH_JWKS_URL'];
  return ['CLERK_JWT_ISSUER_DOMAIN'];
}

/**
 * @param raw          contents of selfhost/.env
 * @param serviceToken resolved AI_CREDENTIAL_SERVICE_TOKEN (from .env, or freshly generated)
 */
export function buildBackendVars(raw, serviceToken) {
  const authMode = readEnvValue(raw, 'AUTH_MODE') || 'clerk';

  const vars = {
    // Decides which provider auth.config.ts builds, so it must be pushed BEFORE
    // the deploy that reads it.
    AUTH_MODE: authMode,
    CLERK_JWT_ISSUER_DOMAIN: readEnvValue(raw, 'CLERK_JWT_ISSUER_DOMAIN') || 'unused',
    // Only meaningful when AUTH_MODE=local. Derived by the app server from its
    // own APP_ORIGIN, so the issuer Convex trusts and the issuer the server
    // stamps into tokens cannot disagree - a mismatch there fails every sign-in
    // with nothing useful in the logs.
    // Convex requires EVERY variable referenced in auth.config.ts to EXIST on
    // the deployment, whether or not the branch reading it is taken - so a
    // clerk-mode install still has to push these, and vice versa. A literal
    // 'unused' is clearer in a dashboard than an empty string, which reads as a
    // value someone forgot to fill in.
    LOCAL_AUTH_ISSUER: readEnvValue(raw, 'LOCAL_AUTH_ISSUER') || 'unused',
    LOCAL_AUTH_JWKS_URL: readEnvValue(raw, 'LOCAL_AUTH_JWKS_URL') || 'unused',
    AI_CREDENTIAL_SERVICE_TOKEN: serviceToken,
    // Encrypts BYOK keys at rest inside Convex. Generated by install.ps1 or the
    // desktop supervisor alongside the service token.
    AI_CREDENTIAL_ENCRYPTION_KEY: readEnvValue(raw, 'AI_CREDENTIAL_ENCRYPTION_KEY') || 'unused',
    // Read by convex/users.ts to decide whether a new sign-up is auto-approved.
    // It MUST be pushed here rather than merely set on the backend process: a
    // Convex function's process.env comes from the DEPLOYMENT's variables, not
    // from the OS environment of convex-local-backend.exe. Setting it only on
    // the process would leave a desktop install silently stranding its first
    // user on the pending-approval screen - the exact failure this removes.
    DEPLOYMENT_MODE: readEnvValue(raw, 'DEPLOYMENT_MODE') || 'server',
    // Not a secret, but Convex must agree with the app tier: documentChunks.ts
    // reads it at module load and it decides which stored key is even relevant.
    EMBEDDING_PROVIDER: readEnvValue(raw, 'EMBEDDING_PROVIDER') || 'voyage',
    RESEND_API_KEY: readEnvValue(raw, 'RESEND_API_KEY'),
    SIGNUP_EMAIL_FROM: readEnvValue(raw, 'SMTP_FROM'),
    ADMIN_NOTIFY_EMAIL: readEnvValue(raw, 'ADMIN_NOTIFY_EMAIL'),
  };

  // Pass-through only, never fabricated: an operator upgrading an install that
  // predates per-company keys may still rely on a shared key in .env, and the
  // resolver keeps env as its last fallback rung. A fresh install has none here
  // and gets its key from the app instead.
  const anthropic = readEnvValue(raw, 'ANTHROPIC_API_KEY');
  if (anthropic) vars.ANTHROPIC_API_KEY = anthropic;

  return vars;
}

/**
 * Issuer URL for local auth, derived from the app origin the browser uses.
 * Must match what the app server stamps into tokens and what Convex is told to trust.
 */
export function localAuthIssuerFor(appOrigin) {
  return `${String(appOrigin || '').replace(/\/+$/, '')}/local-auth`;
}

/** JWKS URL Convex fetches to verify locally-issued tokens. */
export function localAuthJwksUrlFor(appOrigin) {
  return `${localAuthIssuerFor(appOrigin)}/.well-known/jwks.json`;
}

/**
 * Backend variables for a desktop install's first-run Convex deploy.
 *
 * Always derives LOCAL_AUTH_* from the loopback APP_ORIGIN so the issuer Convex
 * trusts cannot drift from the port the supervisor chose. Local accounts are
 * always available on a desktop install; `authMode: 'both'` additionally
 * trusts the hosted Clerk issuer so the user can sign in with their online
 * account. The lines appended here WIN over anything in the env file - the
 * file is where the user's generated secrets live, not where auth is decided.
 *
 * @param {object} options
 * @param {string} options.appOrigin
 * @param {string} options.serviceToken
 * @param {string} [options.envFileRaw]
 * @param {'local'|'both'} [options.authMode]
 * @param {string} [options.clerkIssuerDomain] required when authMode is 'both'
 */
export function buildDesktopBackendVars({
  appOrigin,
  serviceToken,
  envFileRaw = '',
  authMode = 'local',
  clerkIssuerDomain = '',
}) {
  const mode = authMode === 'both' && clerkIssuerDomain ? 'both' : 'local';
  const issuer = localAuthIssuerFor(appOrigin);
  const jwks = localAuthJwksUrlFor(appOrigin);
  // readEnvValue returns the FIRST match, so the derived lines go first.
  const raw = [
    `AUTH_MODE=${mode}`,
    `DEPLOYMENT_MODE=desktop`,
    `LOCAL_AUTH_ISSUER=${issuer}`,
    `LOCAL_AUTH_JWKS_URL=${jwks}`,
    `APP_ORIGIN=${appOrigin}`,
    `CLERK_JWT_ISSUER_DOMAIN=${mode === 'both' ? clerkIssuerDomain : 'unused'}`,
    String(envFileRaw || '').trim(),
  ]
    .filter(Boolean)
    .join('\n');

  return buildBackendVars(raw, serviceToken);
}
