"use node";

/**
 * Sign-in and sign-up for a self-hosted install.
 *
 * "use node" because scrypt is not available in Convex's default runtime, and
 * that constraint turns out to be a feature: verification happens HERE, inside
 * the database tier, so a password hash never has to be handed to the app
 * server to be compared. The app server learns only whether the attempt
 * succeeded and, if so, who it was.
 *
 * These are internal actions. The only route in is the service-token-gated
 * endpoint in convex/http.ts, which the app server calls; a browser has no way
 * to reach them.
 *
 * WHAT THIS DELIBERATELY DOES NOT DO
 * There is no password-reset flow, because there is nowhere to send the mail on
 * an air-gapped install and an unauthenticated reset endpoint would be a better
 * way in than the password. Recovery is an administrator resetting another
 * user's password from inside the app.
 */
import { v } from "convex/values";
import { internal } from "./_generated/api";
import { internalAction } from "./_generated/server";
import { hashPassword, normalizeEmail, validatePassword, verifyPassword, passwordNeedsRehash } from "./lib/passwordHash";
import { verifyAdminAssertion } from "./lib/adminAssertion";

/** What the app server gets back. Never includes a hash. */
type SignInResult =
  | { ok: true; subject: string; email: string; name?: string; isFirstAccount?: boolean }
  | { ok: false; reason: "invalid" | "locked" | "disabled"; message: string };

/**
 * The message shown for a failed sign-in.
 *
 * IDENTICAL whether the address is unknown or the password is wrong. Saying
 * "no account with that email" turns the login form into a tool for discovering
 * which of a company's staff have accounts.
 */
const GENERIC_FAILURE = "That email address and password do not match an account.";

export const signIn = internalAction({
  args: { email: v.string(), password: v.string() },
  handler: async (ctx, args): Promise<SignInResult> => {
    const email = normalizeEmail(args.email);

    const account = await ctx.runQuery(internal.localAuthAccounts._byEmail, { email });

    if (!account) {
      // Hash anyway before answering. Returning immediately makes an unknown
      // address measurably faster than a wrong password, which is enough to
      // enumerate accounts over a few hundred requests.
      verifyPassword(args.password, hashPassword("timing-equalisation"));
      return { ok: false, reason: "invalid", message: GENERIC_FAILURE };
    }

    if (account.disabled) {
      return {
        ok: false,
        reason: "disabled",
        message: "This account has been disabled. Ask an administrator to re-enable it.",
      };
    }

    if (typeof account.lockedUntil === "number" && account.lockedUntil > Date.now()) {
      const minutes = Math.ceil((account.lockedUntil - Date.now()) / 60000);
      return {
        ok: false,
        reason: "locked",
        message: `Too many failed attempts. Try again in ${minutes} minute${minutes === 1 ? "" : "s"}.`,
      };
    }

    if (!verifyPassword(args.password, account.passwordHash)) {
      await ctx.runMutation(internal.localAuthAccounts._recordFailure, { email });
      return { ok: false, reason: "invalid", message: GENERIC_FAILURE };
    }

    if (passwordNeedsRehash(account.passwordHash)) {
      await ctx.runMutation(internal.localAuthAccounts._setPassword, {
        subject: account.subject,
        passwordHash: hashPassword(args.password),
      });
    }

    await ctx.runMutation(internal.localAuthAccounts._recordSuccess, { subject: account.subject });
    return {
      ok: true,
      subject: account.subject,
      email: account.email,
      name: account.name ?? undefined,
    };
  },
});

/**
 * Create an account.
 *
 * `subject` is generated by the app server (which owns the format) and passed
 * in, rather than minted here, so there is one definition of what a local
 * identity looks like.
 */
export const createAccount = internalAction({
  args: {
    subject: v.string(),
    email: v.string(),
    password: v.string(),
    name: v.optional(v.string()),
  },
  handler: async (
    ctx,
    args,
  ): Promise<{ ok: true; subject: string; isFirstAccount: boolean } | { ok: false; message: string }> => {
    const email = normalizeEmail(args.email);
    if (!email.includes("@")) {
      return { ok: false, message: "Enter a valid email address." };
    }

    const policy = validatePassword(args.password);
    if (!policy.ok) return { ok: false, message: policy.message ?? "That password is not acceptable." };

    // Checked BEFORE the insert so the very first account can be granted owner
    // rights, and checked again inside _create against a race.
    const isFirstAccount: boolean = await ctx.runQuery(internal.localAuthAccounts._isEmpty, {});

    try {
      await ctx.runMutation(internal.localAuthAccounts._create, {
        subject: args.subject,
        email,
        passwordHash: hashPassword(args.password),
        name: args.name,
      });
    } catch (err) {
      // The duplicate-email case. Reported plainly: unlike a failed SIGN-IN,
      // this address is one the person is trying to claim, so confirming it is
      // taken tells them nothing they could not learn by trying to sign in.
      return {
        ok: false,
        message: err instanceof Error ? err.message : "The account could not be created.",
      };
    }

    return { ok: true, subject: args.subject, isFirstAccount };
  },
});

/**
 * Whether ANY account exists.
 *
 * Drives the first-run experience: on a fresh install the person at the machine
 * is shown "create your account" rather than a sign-in form that can only fail.
 *
 * Reveals only a boolean about the installation, never anything about who has
 * an account - and anyone who can reach it is already on the machine.
 */
export const hasAccounts = internalAction({
  args: {},
  handler: async (ctx): Promise<{ hasAccounts: boolean }> => {
    const empty: boolean = await ctx.runQuery(internal.localAuthAccounts._isEmpty, {});
    return { hasAccounts: !empty };
  },
});

/**
 * Reset another user's password. THE ONLY RECOVERY PATH on this product.
 *
 * There is no reset email - an install may never touch the internet, and an
 * unauthenticated reset endpoint would be an easier way in than the password.
 * So recovery is deliberately a human one: someone who is already an
 * administrator, already signed in, sets a new password and tells the person.
 *
 * AUTHORISATION IS THE CALLER'S, NOT THE ARGUMENT'S. The `callerSubject` is
 * checked against the users table for an admin role; passing a different
 * subject does not grant anything, because the check is on what that row says,
 * not on what the caller claims to be.
 */
export const adminResetPassword = internalAction({
  args: {
    callerSubject: v.string(),
    targetEmail: v.string(),
    newPassword: v.string(),
    adminAssertion: v.string(),
  },
  handler: async (ctx, args): Promise<{ ok: boolean; message?: string }> => {
    const serviceToken = process.env.AI_CREDENTIAL_SERVICE_TOKEN || "";
    if (!verifyAdminAssertion(serviceToken, args.callerSubject, args.adminAssertion)) {
      return { ok: false, message: "This request could not be verified." };
    }

    const caller = await ctx.runQuery(internal.localAuthAccounts._callerRole, {
      subject: args.callerSubject,
    });
    if (caller !== "admin") {
      return { ok: false, message: "Only an administrator can reset another user's password." };
    }

    const policy = validatePassword(args.newPassword);
    if (!policy.ok) return { ok: false, message: policy.message };

    const target = await ctx.runQuery(internal.localAuthAccounts._byEmail, {
      email: normalizeEmail(args.targetEmail),
    });
    if (!target) return { ok: false, message: "No account with that email address." };

    await ctx.runMutation(internal.localAuthAccounts._setPassword, {
      subject: target.subject,
      passwordHash: hashPassword(args.newPassword),
    });
    return { ok: true };
  },
});

/** Change a password, after proving the current one. */
export const changePassword = internalAction({
  args: { subject: v.string(), currentPassword: v.string(), newPassword: v.string() },
  handler: async (ctx, args): Promise<{ ok: boolean; message?: string }> => {
    const account = await ctx.runQuery(internal.localAuthAccounts._bySubject, {
      subject: args.subject,
    });
    if (!account) return { ok: false, message: "No such account." };

    if (!verifyPassword(args.currentPassword, account.passwordHash)) {
      return { ok: false, message: "Your current password is not correct." };
    }

    const policy = validatePassword(args.newPassword);
    if (!policy.ok) return { ok: false, message: policy.message };

    await ctx.runMutation(internal.localAuthAccounts._setPassword, {
      subject: args.subject,
      passwordHash: hashPassword(args.newPassword),
    });
    return { ok: true };
  },
});
